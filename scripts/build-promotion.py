#!/usr/bin/env python3
"""Generate the committed, buildless GitHub Pages language editions."""
import argparse
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE_URL = 'https://revtel.github.io/react-native-nfc-rewriter/'
LANGUAGES = {'en': '', 'zh-Hant': 'zh-Hant/', 'ja': 'ja/'}
STABLE_TEXT = {
    'NFC Open ReWriter', 'GitHub', 'React Native', 'iOS', 'Android',
    'iOS & Android', 'English · 繁體中文 · 日本語', 'English', '繁體中文',
    '日本語', 'react-native-nfc-manager', 'nfctogo@gmail.com', 'whitedogg13',
    'Revteltech', '01', '02', '03', '↗', '↘', '↓',
}


class LocalizedPage(HTMLParser):
    def __init__(self, language, translations):
        super().__init__(convert_charrefs=False)
        self.language = language
        self.translations = translations
        self.prefix = './' if language == 'en' else '../'
        self.output = []

    def translate(self, text):
        content = text.strip()
        if not content or self.language == 'en' or content in STABLE_TEXT:
            return text
        if content not in self.translations:
            raise ValueError(f'{self.language}: missing translation for {content!r}')
        return text.replace(content, self.translations[content], 1)

    def handle_decl(self, declaration):
        self.output.append(f'<!{declaration}>\n<!-- Generated by scripts/build-promotion.py; edit promotion/site-template.html and promotion/locales/. -->')

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if tag == 'html':
            attrs['lang'] = self.language
        for name in ('alt', 'aria-label'):
            if attrs.get(name):
                attrs[name] = self.translate(attrs[name])
        if tag == 'meta' and (attrs.get('name') == 'description' or attrs.get('property') in {'og:title', 'og:description', 'og:image:alt'}):
            attrs['content'] = self.translate(attrs['content'])
        if tag == 'meta' and attrs.get('property') == 'og:url':
            attrs['content'] = SITE_URL + LANGUAGES[self.language]
        if tag == 'link' and attrs.get('rel') == 'canonical':
            attrs['href'] = SITE_URL + LANGUAGES[self.language]
        for name in ('href', 'src'):
            path = attrs.get(name, '')
            if path.startswith('./assets/screenshots/'):
                attrs[name] = self.prefix + 'assets/screenshots/' + self.language + '/' + path.rsplit('/', 1)[-1]
            elif path.startswith('./assets/') or path == './styles.css':
                attrs[name] = self.prefix + path[2:]
        if tag == 'a' and attrs.get('hreflang') in LANGUAGES:
            target = attrs['hreflang']
            attrs['href'] = self.prefix + LANGUAGES[target]
            if target == self.language:
                attrs['aria-current'] = 'page'
        self.output.append('<' + tag + ''.join(
            f' {name}' if value is None else f' {name}="{escape(value, quote=True)}"'
            for name, value in attrs.items()
        ) + '>')

    def handle_endtag(self, tag):
        if tag == 'head':
            for language, path in LANGUAGES.items():
                self.output.append(f'    <link rel="alternate" hreflang="{language}" href="{SITE_URL}{path}">\n')
            self.output.append(f'    <link rel="alternate" hreflang="x-default" href="{SITE_URL}">\n')
            locale = {'en': 'en_US', 'zh-Hant': 'zh_TW', 'ja': 'ja_JP'}[self.language]
            self.output.append(f'    <meta property="og:locale" content="{locale}">\n  ')
        self.output.append(f'</{tag}>')

    def handle_data(self, data):
        self.output.append(escape(self.translate(data), quote=False))

    def handle_entityref(self, name):
        self.output.append(f'&{name};')

    def handle_charref(self, name):
        self.output.append(f'&#{name};')

    def handle_comment(self, data):
        self.output.append(f'<!--{data}-->')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated pages are out of date.')
    args = parser.parse_args()
    template = (ROOT / 'promotion/site-template.html').read_text()
    for language, path in LANGUAGES.items():
        translations = {} if language == 'en' else json.loads((ROOT / f'promotion/locales/{language}.json').read_text())
        page = LocalizedPage(language, translations)
        page.feed(template)
        rendered = ''.join(page.output)
        output = ROOT / 'docs' / path / 'index.html'
        if args.check:
            if not output.exists() or output.read_text() != rendered:
                raise SystemExit(f'Out of date: {output.relative_to(ROOT)}')
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(rendered)
        print(('Checked ' if args.check else 'Generated ') + str(output.relative_to(ROOT)))


if __name__ == '__main__':
    main()
